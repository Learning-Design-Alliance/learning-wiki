"""
index_report.py — Renders eval/runs/index.html, the landing page python's
`http.server` shows at http://localhost:8080/ (see deploy/eval-harness-web.service).
Answers "how is the whole experiment going" at a glance across every run —
not just one run's own dashboard.

The real question this page is built to answer: for each MODEL, which
PROMPT VERSION gets it closest to 100% validator pass rate with the
highest judge score — the two primary metrics — with cost/latency shown
as secondary context, not competing for attention. A run-wide average
across several unrelated models answers "did the blended batch move,"
not "did this specific model get better," so every table here is built
from per-(run, model) rows (history.collect()), never a cross-model mean.

Regenerated by eval_harness.py's generate_index(), called from the same
generate_reports() hook that already fires after every completed
(model, article) pair — so this page is live while any run is in progress,
same guarantee as an individual run's report.html.
"""

import html
