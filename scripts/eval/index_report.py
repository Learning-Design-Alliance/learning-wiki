"""
index_report.py — Renders eval/runs/index.html, the landing page python's
`http.server` shows at http://localhost:8080/ (see deploy/eval-harness-web.service).
Answers "how is the whole experiment going" at a glance across every run —
not just one run's own dashboard.

The real question this page is built to answer: for each MODEL, which
PROMPT VERSION gets it closest to 100% validator pass rate with the
highest judge score — the two primary metrics — with cost/latency shown
as secondary context, not competing for attention. A run-wide average
across several unrelated models answers "did the blended batch move,"
not "did this specific model get better," so every table here is built
from per-(run, model) rows (history.collect()), never a cross-model mean.

Regenerated by eval_harness.py's generate_index(), called from the same
generate_reports() hook that already fires after every completed
(model, article) pair — so this page is live while any run is in progress,
same guarantee as an individual run's report.html.
"""

import html
import re

from . import html_report, model_catalog

AUTO_REFRESH_MS = html_report.AUTO_REFRESH_MS


def _esc(s) -> str:
    return html.escape(str(s)) if s is not None else ""


def _version_sort_key(version_str: str):
    first = (version_str or "").split(",")[0].strip()
    digits = re.sub(r"\D", "", first)
    return int(digits) if digits else float("inf")


def _best_sort_key(r: dict) -> tuple:
    """Ranks a (run, model) row as a strict priority order, not a weighted
    blend: validator pass rate and completeness are the baseline that must
    reach 100% first (a tuple comparison never lets a higher judge score
    outrank a lower pass rate), and only once those tie does judge score —
    "as close to 5 as possible" — decide the winner. Cost/latency never
    factor into ranking at all; they're shown for context only."""
    pass_rate = r.get("validator_pass_rate")
    completeness = r.get("avg_completeness_score")
    score = r.get("avg_judge_score")
    return (
        pass_rate if pass_rate is not None else -1,
        completeness if completeness is not None else -1,
        score if score is not None else -1,
    )


def _score_str(r: dict) -> str:
    return f"{r['avg_judge_score']:.2f}/5" if r.get("avg_judge_score") is not None else "–"


def _pct_badge_html(frac, css_prefix: str) -> str:
    if frac is None:
        return f'<span class="{css_prefix}">–</span>'
    pct = frac * 100
    cls = f"{css_prefix}-good" if frac >= 1.0 else (f"{css_prefix}-warn" if frac >= 0.7 else f"{css_prefix}-bad")
    return f'<span class="{css_prefix} {cls}">{pct:.0f}%</span>'


def _pass_rate_html(pass_rate) -> str:
    return _pct_badge_html(pass_rate, "pass-rate")


def _completeness_html(completeness) -> str:
    return _pct_badge_html(completeness, "pass-rate")


def _secondary_str(r: dict) -> tuple:
    cost_str = f"${r['cost_per_article_usd']:.4f}" if r.get("cost_per_article_usd") is not None else "–"
    latency_str = f"{r['avg_latency_s']:.1f}s" if r.get("avg_latency_s") is not None else "–"
    return cost_str, latency_str


def _run_row(r: dict) -> str:
    if r["total"]:
        pct = round(100 * r["done"] / r["total"]) if r["total"] else 0
        progress_html = f"""
          <div class="bar-track idx-track"><div class="bar-fill" style="width:{max(2, pct)}%; background:var(--series-1);"></div></div>
          <span class="idx-count">{r['done']}/{r['total']}</span>"""
        status = "Complete" if r["done"] >= r["total"] else "In progress"
    else:
        progress_html = '<span class="idx-count">no queue.json (older run)</span>'
        status = "Unknown"

    score_str = f"{r['best_judge_score']:.2f}/5" if r["best_judge_score"] is not None else "–"
    cost_str = f"${r['total_cost_usd']:.4f}" if r["total_cost_usd"] is not None else "–"
    latency_str = f"{r['avg_latency_s']:.1f}s" if r["avg_latency_s"] is not None else "–"

    return f"""
    <tr class="idx-row">
      <td><a href="./{_esc(r['run_id'])}/report.html">{_esc(r['run_id'])}</a></td>
      <td><span class="badge-status badge-status-{'complete' if status == 'Complete' else 'progress'}">{_esc(status)}</span></td>
      <td class="idx-progress-cell">{progress_html}</td>
      <td class="num idx-emph">{_esc(score_str)}</td>
      <td class="num idx-secondary">{_esc(cost_str)}</td>
      <td class="num idx-secondary">{_esc(latency_str)}</td>
      <td>{_esc(r['n_models'])}</td>
      <td>{_esc(r['prompt_versions'])}</td>
    </tr>"""


def _group_by_model(history_rows: list) -> dict:
    by_model = {}
    for r in history_rows:
        by_model.setdefault(r["model"], []).append(r)
    return by_model


def _leaderboard_table(model_order: list, best_by_model: dict) -> str:
    if not model_order:
        return '<p class="empty-note">No data yet.</p>'
    rows_html = []
    for model in model_order:
        r = best_by_model[model]
        desc = model_catalog.describe(model)
        desc_html = f'<div class="idx-model-desc">{_esc(desc)}</div>' if desc else ""
        cost_str, latency_str = _secondary_str(r)
        rows_html.append(f"""
        <tr>
          <td><span class="idx-model-name">{_esc(model)}</span>{desc_html}</td>
          <td><code>{_esc(r['prompt_version'])}</code></td>
          <td class="num idx-emph">{_pass_rate_html(r.get('validator_pass_rate'))}</td>
          <td class="num idx-emph">{_completeness_html(r.get('avg_completeness_score'))}</td>
          <td class="num idx-emph">{_esc(_score_str(r))}</td>
          <td class="num idx-secondary">{_esc(cost_str)}</td>
          <td class="num idx-secondary">{_esc(latency_str)}</td>
          <td><a href="./{_esc(r['run_id'])}/report.html">{_esc(r['run_id'])}</a></td>
        </tr>""")
    return f"""
    <table class="idx-table leaderboard-table">
      <thead>
        <tr><th>Model</th><th>Best prompt version</th><th>Validator pass rate</th><th>Completeness</th>
            <th>Judge score</th><th class="idx-secondary-th">Cost/article</th>
            <th class="idx-secondary-th">Latency</th><th>Run</th></tr>
      </thead>
      <tbody>{''.join(rows_html)}</tbody>
    </table>"""


def _version_detail_table(model_order: list, by_model_hist: dict, best_by_model: dict) -> str:
    if not model_order:
        return '<p class="empty-note">No data yet.</p>'
    body = []
    for model in model_order:
        rows = sorted(by_model_hist[model], key=lambda r: (_version_sort_key(r["prompt_version"]), r["run_id"]))
        desc = model_catalog.describe(model)
        desc_html = f' <span class="idx-model-desc-inline">({_esc(desc)})</span>' if desc else ""
        body.append(f'<tr class="model-group-header"><td colspan="6">{_esc(model)}{desc_html}</td></tr>')
        best = best_by_model[model]
        for r in rows:
            is_best = r["run_id"] == best["run_id"] and r["prompt_version"] == best["prompt_version"]
            cost_str, latency_str = _secondary_str(r)
            star = " &#9733;" if is_best else ""
            body.append(f"""
        <tr class="{'best-row' if is_best else ''}">
          <td><code>{_esc(r['prompt_version'])}</code>{star}</td>
          <td><a href="./{_esc(r['run_id'])}/report.html">{_esc(r['run_id'])}</a></td>
          <td class="num idx-emph">{_pass_rate_html(r.get('validator_pass_rate'))}</td>
          <td class="num idx-emph">{_completeness_html(r.get('avg_completeness_score'))}</td>
          <td class="num idx-emph">{_esc(_score_str(r))}</td>
          <td class="num idx-secondary">{_esc(cost_str)}</td>
          <td class="num idx-secondary">{_esc(latency_str)}</td>
        </tr>""")
    return f"""
    <table class="idx-table version-table">
      <thead>
        <tr><th>Prompt version</th><th>Run</th><th>Validator pass rate</th><th>Completeness</th>
            <th>Judge score</th><th class="idx-secondary-th">Cost/article</th>
            <th class="idx-secondary-th">Latency</th></tr>
      </thead>
      <tbody>{''.join(body)}</tbody>
    </table>"""


def _trend_chart(history_rows: list, metric_key: str, label: str, unit: str, colors: dict,
                  scale100: bool = False) -> str:
    def scaled(v):
        return v * 100 if scale100 else v

    run_order = []
    for r in history_rows:
        if r["run_id"] not in run_order:
            run_order.append(r["run_id"])

    values = [scaled(r[metric_key]) for r in history_rows if r.get(metric_key) is not None]
    if not run_order or not values:
        return f'<div class="chart-card"><h3>{_esc(label)}</h3><p class="empty-note">No data yet.</p></div>'

    W, H, PAD, PAD_BOTTOM = 560, 220, 46, 40
    plot_w, plot_bottom = W - 2 * PAD, H - PAD_BOTTOM
    n = len(run_order)
    x_step = plot_w / (n - 1) if n > 1 else 0
    y_max = 100 if scale100 else (max(values) * 1.15 or 1)

    def x_for(run_id):
        idx = run_order.index(run_id)
        return PAD + (idx * x_step if n > 1 else plot_w / 2)

    def y_for(v):
        return plot_bottom - (v / y_max) * (plot_bottom - PAD)

    series_parts = []
    for i, model in enumerate(colors):
        slot = (i % len(colors)) + 1
        pts = [(r["run_id"], scaled(r[metric_key])) for r in history_rows
               if r["model"] == model and r.get(metric_key) is not None]
        if not pts:
            continue
        coords = [(x_for(rid), y_for(v), rid, v) for rid, v in pts]
        path_d = "M " + " L ".join(f"{x:.1f} {y:.1f}" for x, y, _, _ in coords)
        dots = "".join(
            f'<circle cx="{x:.1f}" cy="{y:.1f}" r="4" fill="var(--series-{slot})" stroke="var(--surface-1)" '
            f'stroke-width="1.5"><title>{_esc(model)} — {_esc(rid)}: '
            f'{_esc(f"${v}" if unit == "$" else f"{v}{unit}")}</title></circle>'
            for x, y, rid, v in coords
        )
        series_parts.append(
            f'<path d="{path_d}" fill="none" stroke="var(--series-{slot})" stroke-width="2"/>{dots}')

    fracs = (0, 0.25, 0.5, 0.75, 1.0)
    gridlines = "".join(
        f'<line x1="{PAD}" y1="{plot_bottom - f * (plot_bottom - PAD)}" x2="{W - PAD}" '
        f'y2="{plot_bottom - f * (plot_bottom - PAD)}" class="gridline" />'
        for f in fracs
    )
    y_ticks = "".join(
        f'<text x="{PAD - 8}" y="{plot_bottom - f * (plot_bottom - PAD) + 4}" class="axis-label" '
        f'text-anchor="end">{f * y_max:.2g}</text>'
        for f in fracs
    )

    return f"""
    <div class="chart-card">
      <h3>{_esc(label)}</h3>
      <svg viewBox="0 0 {W} {H}" class="trend-svg" role="img" aria-label="{_esc(label)} across runs, one line per model">
        {gridlines}
        <line x1="{PAD}" y1="{plot_bottom}" x2="{W - PAD}" y2="{plot_bottom}" class="axis-line" />
        <line x1="{PAD}" y1="{PAD}" x2="{PAD}" y2="{plot_bottom}" class="axis-line" />
        {y_ticks}
        {''.join(series_parts)}
      </svg>
    </div>"""


def _legend(colors: dict) -> str:
    items = "".join(
        f'<span class="legend-item"><span class="swatch" style="background:var(--series-{i})"></span>{_esc(m)}</span>'
        for i, m in enumerate(colors, start=1)
    )
    return f'<div class="legend">{items}</div>'


STATUS_LABELS = {
    "starting": ("Starting…", "progress"),
    "running": ("Running", "progress"),
    "completed": ("Completed — all rounds improved", "complete"),
    "stopped_no_improvement": ("Stopped — no candidate improved further", "complete"),
    "stopped_no_findings": ("Stopped — nothing left to optimize against", "complete"),
    "stopped_time_budget": ("Stopped — time budget exhausted", "warn"),
    "stopped_error": ("Stopped — error (check the log)", "warn"),
    "stopped_generation_errors": ("Stopped — baseline had generation errors, nothing usable to learn from", "warn"),
    "stopped_interrupted": ("Stopped — interrupted (process died without finishing; check the log)", "warn"),
}


def _auto_optimize_status_html(state: dict) -> str:
    """The answer to "how many rounds are left in this experiment" — a
    round-level progress view, distinct from any one candidate's own
    (model, article) progress bar shown in the run tables below."""
    if not state:
        return ""
    round_num = state.get("round", 0)
    rounds_total = state.get("rounds_total", 0)
    label, cls = STATUS_LABELS.get(state.get("status"), (state.get("status", "unknown"), "progress"))
    remaining = max(0, rounds_total - round_num) if state.get("status") == "running" else 0
    remaining_str = f" &middot; {remaining} round(s) remaining" if remaining else ""
    pct = round(100 * round_num / rounds_total) if rounds_total else 0
    return f"""
    <div class="card auto-status-card">
      <div class="auto-status-row">
        <span class="badge-status badge-status-{cls}">{_esc(label)}</span>
        <span class="auto-status-text">Round {round_num}/{rounds_total}{remaining_str} &middot;
        current run <a href="./{_esc(state.get('current_run_id', ''))}/report.html">{_esc(state.get('current_run_id', '–'))}</a>
        &middot; prompt version <code>{_esc(state.get('prompt_version', '–'))}</code></span>
      </div>
      <div class="bar-track auto-status-track"><div class="bar-fill" style="width:{max(2, pct)}%; background:var(--series-1);"></div></div>
    </div>"""


