def build_prompt(slug, p, causal, texts) -> str:
    out = [f"## Claim page claims/{slug}.md",
           f"Title: {p['title']}", f"Description: {p['description']}", f"H1: {p['h1']}", "",
           "Subclaims, as a JSON list of the exact lines (use these strings as keys):",
           json.dumps(p["subclaims"], ensure_ascii=False, indent=1), "", "## Evidence entries"]
    for anchor, block, _ in p["entries"]:
        out += ["----", block]
        if anchor in causal:
            vs = causal[anchor]
            out.append("Study-validity judge: comparison "
                       + " / ".join(sorted({v["comparison"] for v in vs}))
                       + "; outcome is self-report: " + ("yes" if anchor in p["self_report"] else "no"))
        out.append("")
    seen, total, src = set(), 0, []
    for anchor, (sid, basis, text) in texts.items():
        if sid in seen or total >= MAX_SOURCES:
            continue
        seen.add(sid)
        t = text[:MAX_SOURCE] + ("\n[TRUNCATED]" if len(text) > MAX_SOURCE else "")
        total += len(t)
        src.append(f"### Source for #{anchor} ({basis}: {sid})\n{t}")
    if src:
        out += ["## Cached source text"] + src
    return "\n".join(out)


