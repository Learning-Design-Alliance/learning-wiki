# ---- reading the page ---------------------------------------------------------------------

def load_fm(fm_text: str) -> dict:
    """The frontmatter as YAML, or its flat scalars where YAML refuses it (a stray control
    character in a source title, say)."""
    try:
        return yaml.safe_load(fm_text) or {}
    except yaml.YAMLError:
        return okf_lib.parse_frontmatter_scalars(fm_text.split("\n"))


def read_page(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    m = okf_lib.FRONTMATTER_RE.match(text)
    fm = load_fm(m.group(1)) if m else {}
    body = text[m.end():] if m else text
    clean = re.sub(r"<!--.*?-->", "", body, flags=re.S)
    h1 = okf_lib.TITLE_RE.search(clean)
    subs = [l.strip() for l in (okf_lib.get_section(clean, "Subclaims") or "").splitlines()
            if l.strip() and not l.strip().startswith("<!--")]
    title, entries = clb.units(path)
    return {"text": text, "fm": fm or {}, "title": str((fm or {}).get("title") or title),
            "description": str((fm or {}).get("description") or ""),
            "h1": h1.group(1).strip() if h1 else "", "subclaims": subs, "entries": entries}


def page_digest(slug: str, p: dict) -> str:
    return clb.digest(slug, p["title"], p["description"], p["h1"], "\n".join(p["subclaims"]),
                      *[b for _, b, _ in p["entries"]])


# ---- verdicts -------------------------------------------------------------------------------

def load_verdicts(store: Path) -> dict:
    """(claim, entry) -> [verdict rows from either judge], every digest."""
    out = collections.defaultdict(list)
    for f in (store / "judged.ndjson", store / "confirmed.ndjson"):
        if not f.exists():
            continue
        for line in f.read_text(encoding="utf-8").splitlines():
            try:
                r = json.loads(line)
            except ValueError:
                continue
            if "error" in r or r.get("comparison") is None:
                continue
            out[(r["claim"], r["entry"])].append(r)
    return out


def qualify(slug: str, path: Path, verdicts: dict, include_none_only: bool = False):
    """(True, {anchor: [verdicts]}) or (False, reason). Unless include_none_only, at least one
    entry must be pre-post: a claim whose entries are all `none` is mostly a survey, interview
    or correlational finding, and the 2026-11-04 sample found rewording those added noise
    ("self-reported" on claims that already said "students reported") rather than removing
    causal language."""
    anchors = jsv.causal_anchors(path)
    if not anchors:
        return False, "no causal entry"
    # A claim that also rests on a synthesis or review says more than its causal entries
    # can: the judge reads only those, so rewording the title from them alone loses what
    # the synthesis found (Murphy et al. 2009's meta-analysis on structured discussion,
    # caught in the 2026-11-04 backlog run).
    if re.search(r"^\s+kind:\s*(quant-synthesis|review)\s*$", path.read_text(encoding="utf-8"), re.M):
        return False, "also rests on a synthesis or review"
    got = {}
    for a in sorted(anchors):
        vs = verdicts.get((slug, a))
        if not vs:
            return False, "causal entry not judged"
        bad = [v["comparison"] for v in vs if v["comparison"] not in QUALIFYING]
        if bad:
            return False, f"entry judged {bad[0]}"
        # From an abstract, "none" can be silence: an abstract that names no comparison
        # group is not evidence there was none (judge_study_validity.problems() discounts
        # it the same way). A pre-post reading from an abstract is positive and counts.
        if any(v["comparison"] == "none" and v.get("basis") == "abstract" for v in vs):
            return False, "comparison read as none from an abstract only"
        got[a] = vs
    if not include_none_only and not any(v["comparison"] == "pre-post-single-group"
                                         for vs in got.values() for v in vs):
        return False, "every entry judged none (no pre-post)"
    return True, got


# ---- is the outcome self-report? -----------------------------------------------------------

# The evidence cells (eval/runs/evidence-axes/cells/, committed) code each entry's outcome on
# evidence-dimensions.json's O axis, which has no "self-report" value: the self-report readings
# are motivation-affect (interest, enjoyment, self-efficacy, anxiety) and the free-text values and
# details naming a perception, rating or questionnaire. The judges alone are not enough: on
# isbar-simulation-improves-communication-clarity both said self-report and the cell codes the
# Communication Clarity Scale as skill-performance, which it is (2026-11-04).
SELF_REPORT_OUTCOMES = {"motivation-affect", "attitude-motivation"}
SELF_REPORT_TEXT = re.compile(r"self-?(?:rat|report|assess|perceiv|efficacy)|perceiv|percept|questionnaire|"
                              r"survey|likert|satisf|attitude|confidence|opinion|reported\b|usability|"
                              r"ease of use", re.I)
SELF_WORDING = re.compile(r"\bself-(?:rated|rating|ratings|reported|report|reports|assessed|"
                          r"assessment|perceived)\b", re.I)
_cells = None


def cell_outcomes() -> dict:
    """(claim, entry) -> [(outcome, outcome_detail)] from the committed evidence cells."""
    global _cells
    if _cells is None:
        import evidence_cells
        _cells = collections.defaultdict(list)
        for r in evidence_cells.read():
            for c in r.get("cells") or []:
                o = c.get("O") or {}
                _cells[(r.get("claim"), r.get("entry"))].append((str(o.get("outcome") or ""),
                                                                 str(o.get("outcome_detail") or "")))
    return _cells


def cell_is_self_report(outcome: str, detail: str) -> bool:
    if outcome in SELF_REPORT_OUTCOMES:
        return True
    if outcome in ("other", "?", "") or outcome not in KNOWN_OUTCOMES:
        return bool(SELF_REPORT_TEXT.search(outcome + " " + detail))
    return False      # a coded performance, retention, transfer, time or load outcome


KNOWN_OUTCOMES = {"immediate-performance", "delayed-retention", "near-transfer", "far-transfer",
                  "conceptual-understanding", "skill-performance", "learning-time", "cognitive-load",
                  "motivation-affect", "persistence", "general-achievement", "assessment-accuracy",
                  "other", "?", "attitude-motivation"}


def self_report_anchors(slug: str, causal: dict) -> set:
    """Entries whose outcome is self-report for wording purposes: every judge verdict says
    self-report AND the entry has evidence cells, every one of them a self-report outcome.
    Disagreement, or no cell, means not self-report."""
    out = set()
    for anchor, vs in causal.items():
        cells = cell_outcomes().get((slug, anchor)) or []
        if vs and all(v.get("outcome_measured") == "self-report" for v in vs) and cells \
                and all(cell_is_self_report(o, d) for o, d in cells):
            out.add(anchor)
    return out


