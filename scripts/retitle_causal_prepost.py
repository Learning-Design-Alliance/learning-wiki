# ---- deterministic checks -------------------------------------------------------------------

CODE_LEAD = re.compile(r"^(`[^`]*`\s*)")
LINK_TAIL = re.compile(r"((?:\s*\[→[^\]]*\]\(#[^)\s]*\)[\s,;.]*)+)$")
NUM = re.compile(r"\d+(?:[.,]\d+)*")


def split_sub(line: str):
    lead = CODE_LEAD.match(line)
    lead = lead.group(1) if lead else ""
    tail = LINK_TAIL.search(line[len(lead):])
    tail = tail.group(1) if tail else ""
    return lead.strip(), tail.strip()


def _sub_anchor(line: str):
    m = re.search(r"\]\(#([^)\s]+)\)", line)
    return m.group(1) if m else None


def validate(p: dict, prop: dict) -> list:
    errs = []
    t, d = prop.get("title"), prop.get("description")
    if not isinstance(t, str) or not t.strip() or "\n" in t or len(t) > MAX_TITLE:
        errs.append("title empty, multi-line or over 300 characters")
    elif "[" in t or "]" in t:
        errs.append("square bracket in title")
    if not isinstance(d, str) or not d.strip() or "\n" in d:
        errs.append("description empty or multi-line")
    subs = prop.get("subclaims") or {}
    if not isinstance(subs, dict):
        errs.append("subclaims is not a mapping")
        subs = {}
    for old, new in subs.items():
        if old not in p["subclaims"]:
            errs.append(f"subclaim not on the page: {old[:60]}")
            continue
        if not isinstance(new, str) or not new.strip() or "\n" in new:
            errs.append(f"subclaim empty or multi-line: {old[:60]}")
            continue
        if split_sub(old) != split_sub(new.strip()):
            errs.append(f"code span or link changed: {old[:60]}")
    sr, causal = p.get("self_report", set()), p.get("causal_anchors", set())
    title_ok = bool(causal) and causal <= sr
    for new, old, ok in ([(t, p["title"], title_ok), (d, p["description"], title_ok)]
                         + [(n, o, _sub_anchor(o) in sr) for o, n in subs.items()]):
        if isinstance(new, str) and not ok and len(SELF_WORDING.findall(new)) > len(SELF_WORDING.findall(old or "")):
            errs.append("self-report wording the evidence cells do not support: " + new[:60])
    page = p["text"]
    for s in [t or "", d or ""] + [v for v in subs.values() if isinstance(v, str)]:
        for n in NUM.findall(s):
            if n not in page:
                errs.append(f"number not on the page: {n}")
    return errs


# ---- writing --------------------------------------------------------------------------------

def set_fm_scalar(fm_text: str, key: str, value: str) -> str:
    """Replace `key: ...` (and any indented continuation lines) with a one-line scalar."""
    line = f"{key}: {okf_lib.yaml_escape(value)}"
    pat = re.compile(rf"(?m)^{key}:[^\n]*(?:\n[ \t]+[^\n]*)*")
    if pat.search(fm_text):
        return pat.sub(lambda _: line, fm_text, count=1)
    # no such key: put it after the title (description) or first
    after = re.search(r"(?m)^title:[^\n]*(?:\n[ \t]+[^\n]*)*", fm_text)
    return fm_text[:after.end()] + "\n" + line + fm_text[after.end():] if after else line + "\n" + fm_text


def write_claim(path: Path, p: dict, prop: dict) -> None:
    text = path.read_text(encoding="utf-8")
    m = okf_lib.FRONTMATTER_RE.match(text)
    fm_text, body = m.group(1), text[m.end():]
    new_fm = set_fm_scalar(set_fm_scalar(fm_text, "title", prop["title"].strip()),
                           "description", prop["description"].strip())
    parsed = load_fm(new_fm)
    if parsed.get("title") != prop["title"].strip() or parsed.get("id", path.stem) != p["fm"].get("id", path.stem):
        raise ValueError("frontmatter did not round-trip")
    body = re.sub(r"(?m)^# .+$", lambda _: "# " + prop["title"].strip(), body, count=1)
    subs = prop.get("subclaims") or {}
    if subs:
        sec = re.search(r"(?ms)^## Subclaims[ \t]*\n(.*?)(?=^## |\Z)", body)
        lines = sec.group(1).split("\n")
        for old, new in subs.items():
            hits = [i for i, l in enumerate(lines) if l.strip() == old]
            if len(hits) != 1:
                raise ValueError(f"subclaim found {len(hits)} times: {old[:60]}")
            lines[hits[0]] = new.strip()
        body = body[:sec.start(1)] + "\n".join(lines) + body[sec.end(1):]
    path.write_text(text[:m.start(1)] + new_fm + text[m.end(1):m.end()] + body, encoding="utf-8")


def repoint_links(slug: str, old_titles: set, new_title: str) -> int:
    """Rewrite `[<old title>](...<slug>.md...)` link text across the content folders."""
    n = 0
    for folder in okf_lib.CONTENT_FOLDERS:
        for f in (WIKI_ROOT / folder).glob("*.md"):
            if f.name == "index.md":
                continue
            text = f.read_text(encoding="utf-8")
            if f"{slug}.md" not in text:
                continue
            out, last, changed = [], 0, 0
            for i, j, dest, _ in okf_lib.iter_markdown_links(text):
                target = dest.split("#", 1)[0]
                if not (target == f"../claims/{slug}.md" or target == f"/claims/{slug}.md"
                        or (folder == "claims" and target == f"{slug}.md")):
                    continue
                for old in old_titles:
                    s = i - len(old)
                    if s >= 1 and text[s:i] == old and text[s - 1] == "[":
                        out.append(text[last:s] + new_title)
                        last = i
                        changed += 1
                        break
            if changed:
                f.write_text("".join(out) + text[last:], encoding="utf-8")
                n += changed
    return n


# ---- the run --------------------------------------------------------------------------------

def _reason_holds(reason, old_text: str, self_report: bool) -> bool:
    """A change is kept only with a reason the old text shows: causal words it really
    contains, or a self-report outcome the judges recorded. The rewriter otherwise makes
    synonym swaps ("increased" -> "rose") on lines that were already descriptive."""
    if isinstance(reason, list):
        return any(_reason_holds(r, old_text, self_report) for r in reason)
    if not isinstance(reason, str) or not reason.strip():
        return False
    if ";" in reason or "|" in reason:      # several quoted phrases in one string
        return any(_reason_holds(r, old_text, self_report) for r in re.split(r"[;|]", reason))
    r, old = _norm(reason).strip('"\' .'), _norm(old_text)
    if r == "self-report":
        # an outcome the page already calls reported, rated or perceived needs no "self-rated"
        return self_report and not re.search(r"self-|report|rate[ds]?\b|rating|perceiv|opinion|"
                                             r"express|attitude|satisf", old)
    if DISCLAIMER.search(r):
        # "the gain cannot be attributed to the simulation alone" is the page already saying
        # what this tool would add (2026-11-04: quoted as a reason on a hand-fixed claim)
        return False
    if r in OUTCOME_VERBS or OUTCOME_SUBJECT.search(r):
        # a bare "improved", or one whose subject is the measure ("scores improved"), describes
        # a change; the rewriter quoted it anyway on lines that were already descriptive
        return False
    return len(r) >= 3 and r in old


DISCLAIMER = re.compile(r"\b(?:cannot|can't|could not|not be attributed|not attributable|rule out|"
                        r"no (?:control|comparison)|without (?:a )?(?:control|comparison)|uncontrolled)\b")
OUTCOME_SUBJECT = re.compile(
    r"\b(?:scores?|knowledge|performance|skills?|achievement|ratings?|accuracy|engagement|"
    r"confidence|anxiety|outcomes?|levels?|means?|gains?|proficiency|competence|attitudes?)"
    r"(?:\s+(?:also|all|each|both|significantly|substantially|markedly|steadily))*"
    r"\s+(?:improved|increased|rose|grew|declined|decreased|fell|dropped|changed)\b")


# Words that describe an observed change when the outcome is their subject ("scores
# increased"); quoted alone they are no evidence of causal wording.
OUTCOME_VERBS = {"improved", "improvement", "improvements", "improve", "increased", "increase",
                 "increases", "rose", "gain", "gains", "gained", "higher", "decreased", "decrease",
                 "declined", "reduced", "significant improvement", "significantly improved",
                 "significant gains", "significantly increased"}


def _norm(s: str) -> str:
    return re.sub(r"\s+", " ", s.translate(str.maketrans("\u2018\u2019\u201c\u201d\u2013\u2014",
                                                     "''\"\"--"))).strip().lower()


def gate(p: dict, prop: dict, reasons, causal: dict) -> list:
    """Drop the parts of a proposal that have no reason the old text shows; returns them."""
    reasons = reasons if isinstance(reasons, dict) else {}
    sr = p.get("self_report", set())
    title_sr = bool(causal) and set(causal) <= sr
    dropped = []
    if isinstance(prop.get("title"), str) and prop["title"].strip() != p["title"]:
        if not _reason_holds([reasons.get("title"), reasons.get("description")],
                             p["title"] + " " + p["description"], title_sr):
            dropped.append("title")
            prop["title"], prop["description"] = p["title"], p["description"]
    if isinstance(prop.get("subclaims"), dict):
        for old in list(prop["subclaims"]):
            if not _reason_holds(reasons.get(old), old, _sub_anchor(old) in sr):
                dropped.append(old)
                del prop["subclaims"][old]
    return dropped


def decide(slug, path, p, causal, texts, args, key):
    """Ask, check, validate. Returns a decision record (status, cost) or raises."""
    prompt = build_prompt(slug, p, causal, texts)
    data, cost = call(args.model, REWRITE_SYSTEM, prompt, key, 4000)
    rec = {"slug": slug, "model": args.model, "at": time.strftime("%Y-%m-%d"),
           "old": {"title": p["title"], "description": p["description"], "h1": p["h1"]},
           "entries": {a: sorted({v["comparison"] for v in vs}) for a, vs in causal.items()}}
    if not isinstance(data, dict) or not isinstance(data.get("needs_change"), bool):
        return {**rec, "status": "failed", "error": "malformed rewrite reply"}, cost
    prop = {k: data.get(k) for k in ("title", "description", "subclaims")}
    prop["subclaims"] = {o: n for o, n in (prop.get("subclaims") or {}).items() if o != n} \
        if isinstance(prop.get("subclaims"), dict) else prop.get("subclaims")
    rec.update(needs_change=data["needs_change"], why=data.get("why"))
    rec["reasons"] = data.get("reasons")
    dropped = gate(p, prop, data.get("reasons"), causal)
    if dropped:
        rec["dropped"] = dropped
    unchanged = (prop.get("title") or "").strip() == p["title"] \
        and (prop.get("description") or "").strip() == p["description"] and not prop["subclaims"]
    if not data["needs_change"] or unchanged:
        return {**rec, "needs_change": False, "status": "no-change"}, cost
    rec["proposal"] = prop
    errs = validate(p, prop)
    if errs:
        return {**rec, "status": "invalid", "errors": errs}, cost
    cprompt = ("## Proposed rewording\nTitle: " + prop["title"] + "\nDescription: " + prop["description"]
               + "\nSubclaims:\n" + "\n".join(prop["subclaims"].get(s, s) for s in p["subclaims"])
               + "\n\n## Evidence entries\n" + "\n\n".join(b for _, b, _ in p["entries"]))
    chk, c2 = call(CHECKER, CHECK_SYSTEM, cprompt, key, 9000)
    cost += c2
    if not isinstance(chk, dict) or not isinstance(chk.get("faithful"), bool) \
            or not isinstance(chk.get("causal"), bool):
        return {**rec, "status": "failed", "error": "malformed checker reply"}, cost
    rec["check"] = {"model": CHECKER, **{k: chk.get(k) for k in ("faithful", "causal", "why")}}
    if not chk["faithful"] or chk["causal"]:
        return {**rec, "status": "refused"}, cost
    return {**rec, "status": "accepted"}, cost


def select(pages, args):
    if args.claims:
        want = [c.removeprefix("claims/").removesuffix(".md") for c in args.claims]
        missing = [c for c in want if c not in pages]
        if missing:
            raise SystemExit(f"no claim page: {', '.join(missing)}")
        return want
    if args.new:
        import link_learner_variables as llv
        return sorted(c for c in llv.new_claims() if c in pages)
    # spread across the alphabet, deterministically, so a --limit sample is not all "a"
    return sorted(pages, key=lambda s: hashlib.sha256(s.encode()).hexdigest())


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--claims", nargs="+", metavar="SLUG")
    g.add_argument("--new", action="store_true", help="claims new in the working tree against HEAD")
    g.add_argument("--all", action="store_true")
    m = ap.add_mutually_exclusive_group(required=True)
    m.add_argument("--check", action="store_true", help="propose and record; write no page")
    m.add_argument("--apply", action="store_true", help="write accepted rewordings")
    ap.add_argument("--budget", type=float, default=2.0, help="stop starting calls past this many USD")
    ap.add_argument("--concurrency", type=int, default=6)
    ap.add_argument("--limit", type=int, help="at most N qualifying claims not yet decided")
    ap.add_argument("--model", default=PRIMARY)
    ap.add_argument("--include-none-only", action="store_true",
                    help="also claims whose every causal entry was judged `none` (no pre-post entry)")
    ap.add_argument("--redo", action="store_true", help="ask again about claims already decided")
    ap.add_argument("--store-root", type=Path, default=WIKI_ROOT,
                    help="checkout holding the ignored verdict store and source cache "
                         "(eval/runs/study-validity/, eval/corpus/cache/); default this one")
    ap.add_argument("--report", type=Path, help="also write the proposals as markdown here")
    a = ap.parse_args()

    store = a.store_root / "eval" / "runs" / "study-validity"
    clb.CACHE = a.store_root / "eval" / "corpus" / "cache"
    clb.FT_LOOKUPS = clb.CACHE / "ft-lookups.ndjson"
    verdicts = load_verdicts(store)
    if not verdicts:
        raise SystemExit(f"no study-validity verdicts under {store}")
    pages = {p.stem: p for p in (WIKI_ROOT / "claims").glob("*.md") if p.stem != "index"}
    decisions = {} if a.redo else load_decisions()
    counts, skipped = collections.Counter(), collections.Counter()
    todo, replay = [], []
    for slug in select(pages, a):
        ok, got = qualify(slug, pages[slug], verdicts, a.include_none_only)
        if not ok:
            skipped[got] += 1
            continue
        counts["qualifying"] += 1
        p = read_page(pages[slug])
        p["causal_anchors"], p["self_report"] = set(got), self_report_anchors(slug, got)
        dg = page_digest(slug, p)
        prev = decisions.get((slug, dg))
        if prev:
            counts["already decided"] += 1
            if a.apply and prev["status"] == "accepted" and not prev.get("applied") and prev["digest"] == dg:
                replay.append((slug, p, dg, prev))
            elif a.claims:
                print(f"  {slug}: decided earlier ({prev['status']}"
                      + (", written" if prev.get("applied") else "") + ")")
            continue
        if a.limit is not None and len(todo) >= a.limit:
            continue
        todo.append((slug, p, dg, got))

    key = os.environ.get("OPENROUTER_API_KEY")
    if todo and not key:
        raise SystemExit("OPENROUTER_API_KEY is not set")
    rows_by_claim = {r["claim"]: r for r in clb.ranking(pages)} if todo else {}
    print(f"{counts['qualifying']} qualifying claims, {len(todo)} to ask, {len(replay)} accepted "
          f"earlier to write; skipped: " + ", ".join(f"{k} {n}" for k, n in skipped.most_common()),
          file=sys.stderr)

    results, spent = [], 0.0

    def finish(slug, p, dg, rec):
        rec["digest"] = dg
        rec["applied"] = False
        if a.apply and rec["status"] == "accepted":
            try:
                write_claim(pages[slug], p, rec["proposal"])
                n = repoint_links(slug, {p["title"], p["h1"]} - {""}, rec["proposal"]["title"].strip())
                rec.update(applied=True, links_repointed=n,
                           result_digest=page_digest(slug, read_page(pages[slug])))
            except ValueError as e:
                rec.update(status="invalid", errors=[f"write: {e}"])
        append_decision(rec)
        results.append(rec)

    for slug, p, dg, prev in replay:
        errs = validate(p, prev["proposal"])
        rec = {k: v for k, v in prev.items() if k not in ("applied", "result_digest", "links_repointed")}
        rec["at"] = time.strftime("%Y-%m-%d")
        if errs:
            rec.update(status="invalid", errors=errs)
        finish(slug, p, dg, rec)

    with concurrent.futures.ThreadPoolExecutor(max_workers=a.concurrency) as ex:
        it, futs = iter(todo), {}

        def submit():
            j = next(it, None)
            if j is not None:
                slug, p, dg, got = j
                texts = source_texts(slug, pages[slug], rows_by_claim)
                futs[ex.submit(decide, slug, pages[slug], p, got, texts, a, key)] = j
        for _ in range(a.concurrency):
            submit()
        while futs:
            fut = next(concurrent.futures.as_completed(list(futs)))
            slug, p, dg, _ = futs.pop(fut)
            try:
                rec, cost = fut.result()
            except Exception as e:  # noqa: BLE001 - a failed call is asked again next run
                print(f"  {slug}: {e}", file=sys.stderr)
                counts["failed call"] += 1
                rec, cost = None, 0.0
            spent += cost
            if rec is not None:
                if rec["status"] == "failed":
                    counts["failed call"] += 1
                    print(f"  {slug}: {rec.get('error')}", file=sys.stderr)
                else:
                    finish(slug, p, dg, rec)
                    if a.claims:
                        print(f"  {slug}: needs_change {rec.get('needs_change')}, {rec['status']}")
            if spent < a.budget:
                submit()
            else:
                counts["not asked (budget)"] = len(todo) - len(results) - counts["failed call"] - len(futs)

    st = collections.Counter(r["status"] for r in results)
    print(f"qualifying {counts['qualifying']} (already decided {counts['already decided']}), "
          f"asked {len(todo) - counts.get('not asked (budget)', 0)}, "
          f"needs change {sum(1 for r in results if r.get('needs_change'))}, "
          f"no change {st['no-change']}, accepted {st['accepted']}, "
          f"written {sum(1 for r in results if r.get('applied'))}, refused by checker {st['refused']}, "
          f"failed validation {st['invalid']}, failed calls {counts['failed call']}"
          + (f", not asked (budget) {counts['not asked (budget)']}" if counts.get("not asked (budget)") else "")
          + f", cost ${spent:.2f}")
    if a.report:
        write_report(a.report, results)


def write_report(path: Path, results: list) -> None:
    out = ["# Causal wording on pre-post claims: proposals", ""]
    for r in sorted(results, key=lambda r: (r["status"], r["slug"])):
        out.append(f"## {r['slug']}")
        out.append(f"- status: **{r['status']}**" + (" (written)" if r.get("applied") else "")
                   + f"; entries: " + ", ".join(f"{k} {'/'.join(v)}" for k, v in r.get("entries", {}).items()))
        out.append(f"- old title: {r['old']['title']}")
        prop = r.get("proposal") or {}
        if prop:
            out.append(f"- new title: {prop.get('title')}")
            if prop.get("description") != prop.get("title"):
                out.append(f"- old description: {r['old']['description']}")
                out.append(f"- new description: {prop.get('description')}")
            for o, n in (prop.get("subclaims") or {}).items():
                out += [f"- old subclaim: {o}", f"- new subclaim: {n}"]
        out.append(f"- rewriter: {r.get('why')}")
        if r.get("check"):
            c = r["check"]
            out.append(f"- checker: faithful {c['faithful']}, causal {c['causal']}: {c.get('why')}")
        if r.get("errors"):
            out.append("- validation: " + "; ".join(r["errors"]))
        out.append("")
    path.write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    main()
