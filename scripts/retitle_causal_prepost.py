#!/usr/bin/env python3
"""
retitle_causal_prepost.py — reword a causal claim whose only evidence is a before-and-after
change in one group.

A claim titled "X improves Y" whose every causal study measured one group before and after,
with no comparison group, rests on a change, not on a cause: the scores rose, and nothing in
the design says the intervention raised them. The study-validity judge
(judge_study_validity.py) records, per causal evidence entry, what the effect was measured
against. This reads those verdicts, and for each claim on which EVERY causal entry was judged
`pre-post-single-group` (or `none`) by every judge that read it, asks one model to reword the
title, description, H1 and subclaims to what was observed, and a second model from another
provider whether the rewording is faithful and free of causal language. Only a rewording both
accept, and that passes the deterministic checks below, is written.

Which claims qualify. The causal entries are counted from the page (`causal_anchors()`), not
from the store, so an entry nobody has judged means "skip", never "qualifies". Verdicts are
matched by claim and entry anchor rather than by digest, because the comparison is a property
of the study and a retitle changes every digest on the page. Any verdict on any of the entries
that says `randomised`, `non-randomised-groups`, `comparison-also-treated` or `unclear` skips
the claim: other evidence may justify the causal wording.

Deterministic checks, before a write: the slug and `id:` are untouched; every changed
subclaim keeps its leading code span (`q2 i?`) and trailing `[-> Author Year](#anchor)` links
byte-identical; the title is one line, non-empty and at most 300 characters; no number appears
that is not already on the page; no square bracket enters a title (it is link text elsewhere).

What it writes (--apply): frontmatter `title:` and `description:`, the `# H1`, the changed
subclaim lines, and the link text `[<old title>](...<slug>.md)` on every citing page in the
content folders (index.md files are regenerated by build_indexes.py, so are left alone).
Nothing else: no codes, no evidence entry, no marker, no DOI, no `verified:`.

Every decision goes to eval/causal-wording/decisions.ndjson (committed, append-only), keyed by
slug and a digest of what was read, so a decided claim is not asked again; a --check proposal
both models accepted is applied later from the record without a second call.

    python3 scripts/retitle_causal_prepost.py --check --claims slug-a slug-b
    python3 scripts/retitle_causal_prepost.py --check --all --limit 40
    python3 scripts/retitle_causal_prepost.py --apply --new            # a batch's new claims
    python3 scripts/retitle_causal_prepost.py --apply --all --budget 20
"""
